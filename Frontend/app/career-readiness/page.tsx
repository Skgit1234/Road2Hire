"use client";

import Link from "next/link";
import { useEffect, useState } from "react";
import { useAuth } from "@/components/auth/AuthProvider";
import { getPipelineCareerReadiness } from "@/lib/pipeline-api";
import type { CareerReadinessPredictionResponse } from "@/lib/pipeline-types";

type RequestState = "loading" | "success" | "empty" | "validation" | "error";

function isNotFoundError(error: unknown): boolean {
  return typeof error === "object" &&
    error !== null &&
    "status" in error &&
    error.status === 404;
}

function formatLabel(value: string): string {
  return value
    .replace(/[_-]+/g, " ")
    .replace(/\b\w/g, (letter) => letter.toUpperCase());
}

function formatDate(value: string | null): string {
  if (!value) return "Not available";
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? "Not available" : date.toLocaleString();
}

export default function CareerReadinessPage() {
  const { session } = useAuth();
  const [state, setState] = useState<RequestState>("loading");
  const [result, setResult] = useState<CareerReadinessPredictionResponse | null>(null);
  const [error, setError] = useState("");

  useEffect(() => {
    if (!session) return;

    let active = true;

    void Promise.resolve()
      .then(() => {
        if (!active) return undefined;
        setState("loading");
        setResult(null);
        setError("");
        return getPipelineCareerReadiness(session.accessToken);
      })
      .then((response) => {
        if (!response || !active) return;
        setResult(response);
        setState("success");
      })
      .catch((requestError: unknown) => {
        if (!active) return;

        if (isNotFoundError(requestError)) {
          setResult(null);
          setState("empty");
          return;
        }

        const message = requestError instanceof Error
          ? requestError.message
          : "Could not load career readiness.";

        setError(message);
        setState(
          message === "The API returned an invalid career-readiness response."
            ? "validation"
            : "error",
        );
      });

    return () => {
      active = false;
    };
  }, [session]);

  const probabilities = result
    ? Object.entries(result.class_probabilities).sort((a, b) => b[1] - a[1])
    : [];

  const warnings = result
    ? [...result.ood_warnings, ...result.pipeline_warnings]
    : [];

  return (
    <div className="min-h-screen bg-background px-4 pb-8 pt-16 sm:px-6 md:py-8 lg:px-8">
      <div className="mx-auto max-w-[1440px]">
        <header className="mb-6 flex flex-col gap-4 border-b border-slate-200 pb-6 sm:flex-row sm:items-end sm:justify-between">
          <div>
            <p className="mb-1 text-sm font-semibold text-primary">Career Assessment</p>
            <h1 className="text-3xl font-bold tracking-tight text-slate-900">Career readiness</h1>
            <p className="mt-2 max-w-2xl text-sm leading-6 text-slate-500">
              View the readiness prediction generated by your latest completed AI pipeline analysis.
            </p>
          </div>
          <span className="inline-flex w-fit items-center gap-2 rounded-full border border-indigo-100 bg-white px-3 py-1.5 text-xs font-medium text-slate-500">
            <span className={`h-2 w-2 rounded-full ${state === "success" ? "bg-emerald-500" : "bg-indigo-500"}`} />
            {state === "success" ? "AI assessment" : "Account assessment"}
          </span>
        </header>

        {!session ? (
          <section className="rounded-2xl border border-amber-200 bg-white p-6 text-sm text-amber-900" role="status">
            Sign in to view the career-readiness assessment for your account.{" "}
            <Link className="font-semibold underline" href="/login">Go to sign in</Link>
          </section>
        ) : state === "loading" ? (
          <section className="rounded-2xl border border-slate-200 bg-white p-6 text-sm text-slate-600" role="status" aria-live="polite">
            Loading your latest career-readiness prediction...
          </section>
        ) : state === "error" || state === "validation" ? (
          <section className="rounded-2xl border border-rose-200 bg-white p-6 text-sm text-rose-800" role="alert">
            <h2 className="font-semibold">
              {state === "validation"
                ? "Career-readiness response could not be validated"
                : "Career readiness could not be loaded"}
            </h2>
            <p className="mt-2">{error}</p>
          </section>
        ) : state === "empty" ? (
          <section className="rounded-2xl border border-slate-200 bg-white p-6 sm:p-8" aria-labelledby="no-analysis-heading">
            <h2 id="no-analysis-heading" className="text-xl font-semibold text-slate-900">
              No completed readiness assessment yet
            </h2>
            <p className="mt-2 max-w-2xl text-sm leading-6 text-slate-600">
              Complete a Skill Gap analysis first. Career readiness becomes available after the AI pipeline completes successfully.
            </p>
            <Link
              href="/skill-gap"
              className="mt-5 inline-flex min-h-11 items-center justify-center rounded-xl bg-primary px-4 py-3 text-sm font-semibold text-white hover:bg-primary-dark"
            >
              Run skill-gap analysis
            </Link>
          </section>
        ) : result && (
          <div className="space-y-5">
            <div className="grid items-start gap-5 lg:grid-cols-[minmax(0,1.2fr)_minmax(280px,0.8fr)]">
              <section className="rounded-2xl border border-slate-200 bg-white p-5 shadow-sm sm:p-7" aria-labelledby="prediction-heading">
                <p className="text-sm font-medium text-slate-500">Predicted readiness class</p>
                <h2 id="prediction-heading" className="mt-2 text-4xl font-bold tracking-tight text-slate-900">
                  {formatLabel(result.predicted_class)}
                </h2>
                <p className="mt-3 text-sm leading-6 text-slate-600">
                  This is the class predicted by the readiness model. It is not a guaranteed employment outcome or a score out of 100.
                </p>

                <div className="mt-7 border-t border-slate-100 pt-5">
                  <h3 className="text-sm font-semibold text-slate-900">Class probabilities</h3>
                  <p className="mt-1 text-xs text-slate-500">
                    The model&apos;s estimated probability for each readiness class.
                  </p>
                  <div className="mt-5 space-y-4">
                    {probabilities.map(([label, probability]) => {
                      const percentage = Math.round(probability * 100);
                      const barWidth = Math.max(0, Math.min(100, probability * 100));

                      return (
                        <div key={label}>
                          <div className="mb-1.5 flex items-center justify-between gap-3 text-sm">
                            <span className="font-medium text-slate-700">{formatLabel(label)}</span>
                            <span className="font-semibold tabular-nums text-slate-900">{percentage}%</span>
                          </div>
                          <div
                            className="h-2.5 overflow-hidden rounded-full bg-slate-100"
                            role="progressbar"
                            aria-label={`${formatLabel(label)} probability`}
                            aria-valuemin={0}
                            aria-valuemax={100}
                            aria-valuenow={percentage}
                          >
                            <div
                              className="h-full rounded-full bg-primary"
                              style={{ width: `${barWidth}%` }}
                            />
                          </div>
                        </div>
                      );
                    })}
                    {probabilities.length === 0 && (
                      <p className="text-sm text-slate-500">No class probabilities were returned.</p>
                    )}
                  </div>
                </div>

                <dl className="mt-6 grid gap-4 border-t border-slate-100 pt-5 sm:grid-cols-2">
                  <div>
                    <dt className="text-xs font-medium text-slate-500">Pipeline run</dt>
                    <dd className="mt-1 font-semibold text-slate-900">#{result.pipeline_run_id}</dd>
                  </div>
                  <div>
                    <dt className="text-xs font-medium text-slate-500">Resume</dt>
                    <dd className="mt-1 font-semibold text-slate-900">#{result.resume_id}</dd>
                  </div>
                  <div>
                    <dt className="text-xs font-medium text-slate-500">Completed</dt>
                    <dd className="mt-1 text-sm text-slate-700">{formatDate(result.completed_at)}</dd>
                  </div>
                  <div>
                    <dt className="text-xs font-medium text-slate-500">Model version</dt>
                    <dd className="mt-1 text-sm text-slate-700">{result.model_version ?? "Not reported"}</dd>
                  </div>
                </dl>
              </section>

              <section className="rounded-2xl border border-slate-200 bg-white p-5 shadow-sm sm:p-6" aria-labelledby="reliability-heading">
                <h2 id="reliability-heading" className="text-base font-semibold text-slate-900">Model reliability information</h2>
                <div className="mt-5 space-y-4">
                  <div className="rounded-xl bg-slate-50 p-4">
                    <p className="text-xs font-medium text-slate-500">Experimental model</p>
                    <p className="mt-1 text-sm font-semibold text-slate-900">
                      {result.is_experimental === null ? "Not reported" : result.is_experimental ? "Yes — experimental" : "No"}
                    </p>
                  </div>
                  <div className="rounded-xl bg-slate-50 p-4">
                    <p className="text-xs font-medium text-slate-500">Out-of-distribution check</p>
                    <p className="mt-1 text-sm font-semibold text-slate-900">
                      {result.is_ood === null ? "Not reported" : result.is_ood ? "Potentially outside training distribution" : "No out-of-distribution flag"}
                    </p>
                  </div>
                  <div className="rounded-xl bg-slate-50 p-4">
                    <p className="text-xs font-medium text-slate-500">Training samples</p>
                    <p className="mt-1 text-sm font-semibold text-slate-900">
                      {result.training_sample_count ?? "Not reported"}
                    </p>
                  </div>
                  <div className="rounded-xl bg-slate-50 p-4">
                    <p className="text-xs font-medium text-slate-500">Model type</p>
                    <p className="mt-1 text-sm font-semibold text-slate-900">{result.model_type ?? "Not reported"}</p>
                  </div>
                </div>
              </section>
            </div>

            {warnings.length > 0 && (
              <section className="rounded-2xl border border-amber-200 bg-white p-5 sm:p-6" aria-labelledby="warnings-heading">
                <h2 id="warnings-heading" className="font-semibold text-amber-900">Assessment warnings</h2>
                <ul className="mt-3 list-inside list-disc space-y-2 text-sm leading-6 text-amber-900">
                  {warnings.map((warning, index) => <li key={`${warning}-${index}`}>{warning}</li>)}
                </ul>
              </section>
            )}

            {result.limitations.length > 0 && (
              <section className="rounded-2xl border border-slate-200 bg-white p-5 sm:p-6" aria-labelledby="limitations-heading">
                <h2 id="limitations-heading" className="font-semibold text-slate-900">Model limitations</h2>
                <ul className="mt-3 list-inside list-disc space-y-2 text-sm leading-6 text-slate-600">
                  {result.limitations.map((limitation, index) => <li key={`${limitation}-${index}`}>{limitation}</li>)}
                </ul>
              </section>
            )}

            <div className="flex flex-wrap gap-3">
              <Link
                href="/skill-gap"
                className="inline-flex min-h-11 items-center justify-center rounded-xl border border-slate-200 bg-white px-4 py-2 text-sm font-semibold text-slate-700 hover:bg-slate-50"
              >
                View skill-gap analysis
              </Link>
              <Link
                href="/learning-roadmap"
                className="inline-flex min-h-11 items-center justify-center rounded-xl bg-primary px-4 py-2 text-sm font-semibold text-white hover:bg-primary-dark"
              >
                View learning roadmap
              </Link>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}